const assert = require('node:assert/strict');
require('../daily-plan.js');
const {plan,FEED,PREP} = globalThis.CRARC_PLAN;
const people=Array.from({length:6},(_,i)=>({id:String(i),nombre:`Persona ${i}`,llegada:'2026-10-13',salida:'2026-10-20',dia_libre:null,tarea_manana:'Limpieza'}));
const count=(items,task)=>items.filter(t=>!t.libre && t.tarde===task).length;
const first=plan(people,[],'2026-10-13');
const second=plan(people,[],'2026-10-14');
const third=plan(people,[],'2026-10-15');
for(const day of [first,second,third]){assert.equal(count(day,FEED),3);assert.equal(count(day,PREP),3);}
first.forEach(t=>{assert.notEqual(t.tarde,second.find(x=>x.estadia_id===t.estadia_id).tarde);assert.equal(t.tarde,third.find(x=>x.estadia_id===t.estadia_id).tarde);});
const saved=first.map(({saved,...t})=>t);
assert.deepEqual(plan(people,saved,'2026-10-14'),second);
const odd=plan(people.slice(0,5),[],'2026-10-13');
assert.equal(Math.abs(count(odd,FEED)-count(odd,PREP)),1);
const free=[{estadia_id:'0',fecha:'2026-10-14',libre:true,manana:'',tarde:''}];
const holiday=plan(people,free,'2026-10-14');
assert.equal(holiday.find(t=>t.estadia_id==='0').libre,true);
assert.equal(count(holiday,FEED)+count(holiday,PREP),5);
assert.equal(plan(people,[],'2026-10-20').length,0);
const manual=people.map(p=>({estadia_id:p.id,fecha:'2026-10-14',libre:false,manana:'Limpieza',tarde:FEED}));
assert.equal(count(plan(people,manual,'2026-10-14'),FEED),6);
const balanced=plan(people,manual,'2026-10-14',true);
assert.equal(count(balanced,FEED),3);assert.equal(count(balanced,PREP),3);
const returning=plan(people,[...saved,...free],'2026-10-15');
assert.notEqual(returning.find(t=>t.estadia_id==='0').tarde,first.find(t=>t.estadia_id==='0').tarde);
const arrivals=[...people,{id:'new',llegada:'2026-10-14',salida:'2026-10-16',dia_libre:null,tarea_manana:'Limpieza'}];
assert.equal(plan(arrivals,[],'2026-10-13').length,6);
const seven=plan(arrivals,[],'2026-10-14');assert.equal(seven.length,7);assert.equal(Math.abs(count(seven,FEED)-count(seven,PREP)),1);
console.log('PASS: 6 personas 3/3, alternancia diaria, dias libres, impar, llegadas, salidas y cambios manuales.');
